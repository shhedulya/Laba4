// Задание 3. Ввести стартовое количество товара S (0..100). Меню do-while: 1 - добавить партию 1..30, 2 - отгрузить партию 1..30, 3 - показать остаток, 0 - выход. Максимальный запас - 100; отгрузка не может превышать остаток. Неверные операции не влияют на запас. Посчитать суммарно принятое и отгруженное количество.
#include <iostream>
#include <clocale>
using namespace std;

void task3()
{
    setlocale(LC_ALL, "Russian");
    int s, k, x;
    int in = 0;
    int out = 0;
    cout << "Введите стартовое количество товара (0..100): ";
    while (!(cin >> s) || s < 0 || s > 100)
    {
        cin.clear();
        cin.ignore(10000, '\n');
        cout << "Нужно число от 0 до 100. Повторите ввод: ";
    }
    do
    {
        cout << endl;
        cout << "1 - добавить партию" << endl;
        cout << "2 - отгрузить партию" << endl;
        cout << "3 - показать остаток" << endl;
        cout << "0 - выход" << endl;
        cout << "Ваш выбор: ";
        while (!(cin >> k) || k < 0 || k > 3)
        {
            cin.clear();
            cin.ignore(10000, '\n');
            cout << "Нужно число от 0 до 3. Повторите ввод: ";
        }
        if (k == 1 || k == 2)
        {
            cout << "Размер партии (1..30): ";
            while (!(cin >> x) || x < 1 || x > 30)
            {
                cin.clear();
                cin.ignore(10000, '\n');
                cout << "Нужно число от 1 до 30. Повторите ввод: ";
            }
        }
        if (k == 1)
        {
            if (s + x > 100)
            {
                cout << "Нельзя: запас станет больше 100" << endl;
            }
            else
            {
                s = s + x;
                in = in + x;
                cout << "Принято " << x << endl;
            }
        }
        else if (k == 2)
        {
            if (x > s)
            {
                cout << "Нельзя: на складе только " << s << endl;
            }
            else
            {
                s = s - x;
                out = out + x;
                cout << "Отгружено " << x << endl;
            }
        }
        else if (k == 3)
        {
            cout << "Остаток: " << s << endl;
        }
    } while (k != 0);
    cout << "Всего принято: " << in << endl;
    cout << "Всего отгружено: " << out << endl;
}

