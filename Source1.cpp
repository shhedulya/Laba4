// Задание 1. Ввести начальный запас S (0..500) и количество операций n (1..30). В цикле for вводить изменение запаса d (-50..50): положительное число - приход, отрицательное - отгрузка. Если изменение сделает запас отрицательным или больше 500, отклонить операцию без изменения запаса. Вывести запас после каждой операции, число отклонённых операций и максимальный достигнутый запас (включая начальный).
#include <iostream>
#include <clocale>
using namespace std;

void task1()
{
    setlocale(LC_ALL, "Russian");
    int s, n, d;
    int rejected = 0;
    cout << "Введите начальный запас (0..500): ";
    while (!(cin >> s) || s < 0 || s > 500)
    {
        cin.clear();
        cin.ignore(10000, '\n');
        cout << "Нужно число от 0 до 500. Повторите ввод: ";
    }
    cout << "Введите количество операций (1..30): ";
    while (!(cin >> n) || n < 1 || n > 30)
    {
        cin.clear();
        cin.ignore(10000, '\n');
        cout << "Нужно число от 1 до 30. Повторите ввод: ";
    }
    int mx = s;
    for (int i = 1; i <= n; i++)
    {
        cout << "Операция " << i << ", изменение запаса (-50..50): ";
        while (!(cin >> d) || d < -50 || d > 50)
        {
            cin.clear();
            cin.ignore(10000, '\n');
            cout << "Нужно число от -50 до 50. Повторите ввод: ";
        }
        if (s + d < 0 || s + d > 500)
        {
            cout << "Операция отклонена" << endl;
            rejected++;
        }
        else
        {
            s = s + d;
        }
        if (s > mx)
        {
            mx = s;
        }
        cout << "Запас: " << s << endl;
    }
    cout << "Отклонено операций: " << rejected << endl;
    cout << "Максимальный запас: " << mx << endl;
}

